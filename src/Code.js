/**
 * calendar-gas
 *
 * Read-only calendar digest API. It reads the owner's calendars for one
 * day and answers only the questions other automations (e.g. alarm-gas)
 * need for the "heading home" decision:
 *
 *   - Is there a plan in the evening (the owner will not come straight
 *     home), and if so, when does the last one end?
 *   - Until when do the day's (pre-evening) commitments run?
 *
 * Event titles are never returned and never logged. The response only
 * carries booleans and timestamps.
 *
 * Every request needs the API_TOKEN script property:
 *   GET ?token=...[&date=YYYY-MM-DD]
 *     -> {"ok":true,"date":"2026-11-24","hasNightPlan":true,
 *         "nightPlanEnd":"2026-11-24T12:30:00.000Z",
 *         "lastWorkEventEnd":"2026-11-24T09:00:00.000Z"}
 *   "date" defaults to today (Asia/Tokyo). Timestamps are ISO 8601 UTC.
 *
 * Definitions (EVENING_START_HOUR, default 17):
 *   - Night plan: a kept event whose start is at/after the evening
 *     start. All-day events and declined events never count.
 *   - lastWorkEventEnd: the latest end among kept events that start
 *     before the evening start (e.g. a 16:00-18:30 meeting counts here,
 *     not as a night plan).
 *
 * Schedule RSS (for the owner's own reader), following the social-gas
 * pattern:
 *   GET ?action=rss&token=<RSS_TOKEN>
 *     -> RSS 2.0 with the events from today (Asia/Tokyo) through the
 *        next 7 days, from both calendars, newest first.
 * Unlike the digest, the feed carries event titles — that is its
 * purpose — so it is guarded by its own RSS_TOKEN, separate from
 * API_TOKEN, and refuses every request while the property is unset
 * or the token mismatches. The family calendar is NOT filtered by
 * EXCLUDE_WORDS here (the owner chose the full family schedule for
 * his own reading); declined events are dropped, all-day events are
 * included.
 *
 * Nothing personal is hardcoded. Script properties:
 *   API_TOKEN          shared secret (generated by setup())
 *   RSS_TOKEN          shared secret for the RSS feed (setup())
 *   MAIN_CALENDAR_ID   the owner's main calendar id
 *   FAMILY_CALENDAR_ID the shared family calendar id
 *   EXCLUDE_WORDS      comma-separated title words; family-calendar
 *                      events whose title contains one are ignored
 *                      (e.g. events that belong to other family members)
 *   EVENING_START_HOUR optional, default 17
 *
 * Run setup() once from the editor: it generates API_TOKEN and
 * RSS_TOKEN and logs so they can be copied. Calendar ids and exclude
 * words are then set in Project Settings.
 */

const DEFAULT_EVENING_START_HOUR = 17;

export function doGet(e) {
  const params = (e && e.parameter) || {};
  if (params.action === 'rss') {
    return serveRss_(params);
  }
  if (!isAuthorized_(params.token)) {
    return createJsonResponse_({ ok: false, error: 'Unauthorized.' });
  }
  const date = params.date || todayJst_();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    return createJsonResponse_({ ok: false, error: 'Invalid date.' });
  }
  const config = readConfig_();
  if (!config) {
    return createJsonResponse_({ ok: false, error: 'Not configured.' });
  }
  return createJsonResponse_(summarizeDay_(date, config));
}

function isAuthorized_(token) {
  const expected = PropertiesService.getScriptProperties().getProperty('API_TOKEN');
  return !!expected && typeof token === 'string' && token.length > 0 && token === expected;
}

function readConfig_() {
  const props = PropertiesService.getScriptProperties();
  const mainId = props.getProperty('MAIN_CALENDAR_ID');
  const familyId = props.getProperty('FAMILY_CALENDAR_ID');
  if (!mainId || !familyId) return null;
  const excludeWords = (props.getProperty('EXCLUDE_WORDS') || '')
    .split(',')
    .map((w) => w.trim())
    .filter((w) => w.length > 0);
  const rawHour = props.getProperty('EVENING_START_HOUR');
  const hour = rawHour === null || rawHour === '' ? NaN : Number(rawHour);
  return {
    mainId,
    familyId,
    excludeWords,
    eveningStartHour: Number.isInteger(hour) && hour >= 0 && hour <= 23 ? hour : DEFAULT_EVENING_START_HOUR,
  };
}

function todayJst_() {
  return Utilities.formatDate(new Date(), 'Asia/Tokyo', 'yyyy-MM-dd');
}

// Asia/Tokyo is UTC+9 year-round (no DST), so JST wall-clock times can
// be built deterministically from UTC.
function jstTime_(dateStr, hour) {
  const [y, m, d] = dateStr.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d, hour - 9, 0, 0, 0));
}

function nextDateStr_(dateStr) {
  return addDaysStr_(dateStr, 1);
}

function addDaysStr_(dateStr, days) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const next = new Date(Date.UTC(y, m - 1, d + days));
  const pad = (n) => String(n).padStart(2, '0');
  return `${next.getUTCFullYear()}-${pad(next.getUTCMonth() + 1)}-${pad(next.getUTCDate())}`;
}

function summarizeDay_(dateStr, config) {
  const dayStart = jstTime_(dateStr, 0);
  const dayEnd = jstTime_(nextDateStr_(dateStr), 0);
  const eveningStart = jstTime_(dateStr, config.eveningStartHour);

  const events = [
    ...readCalendarEvents_(config.mainId, dayStart, dayEnd, []),
    ...readCalendarEvents_(config.familyId, dayStart, dayEnd, config.excludeWords),
  ];
  const summary = summarizeEvents_(events, eveningStart);
  return { ok: true, date: dateStr, ...summary };
}

function readCalendarEvents_(calendarId, start, end, excludeWords) {
  const calendar = CalendarApp.getCalendarById(calendarId);
  if (!calendar) return [];
  return calendar.getEvents(start, end).map((ev) => normalizeEvent_(ev, excludeWords));
}

function normalizeEvent_(ev, excludeWords) {
  const title = typeof ev.getTitle === 'function' ? ev.getTitle() : '';
  let declined = false;
  if (typeof ev.getMyStatus === 'function' && typeof CalendarApp !== 'undefined' && CalendarApp.GuestStatus) {
    declined = ev.getMyStatus() === CalendarApp.GuestStatus.NO;
  }
  return {
    start: ev.getStartTime(),
    end: ev.getEndTime(),
    allDay: typeof ev.isAllDayEvent === 'function' ? ev.isAllDayEvent() : false,
    declined,
    excluded: excludeWords.some((w) => title.includes(w)),
  };
}

export function summarizeEvents_(events, eveningStart) {
  let nightPlanEnd = null;
  let lastWorkEventEnd = null;
  for (const ev of events) {
    if (ev.allDay || ev.declined || ev.excluded) continue;
    if (ev.start >= eveningStart) {
      if (!nightPlanEnd || ev.end > nightPlanEnd) nightPlanEnd = ev.end;
    } else {
      if (!lastWorkEventEnd || ev.end > lastWorkEventEnd) lastWorkEventEnd = ev.end;
    }
  }
  return {
    hasNightPlan: !!nightPlanEnd,
    nightPlanEnd: nightPlanEnd ? nightPlanEnd.toISOString() : null,
    lastWorkEventEnd: lastWorkEventEnd ? lastWorkEventEnd.toISOString() : null,
  };
}

// --- Schedule RSS ---
// The feed window: today (Asia/Tokyo) plus the next 7 days.
const RSS_DAYS_AHEAD_ = 7;
const RSS_LIMIT_ = 200;
const RSS_CHANNEL_ = {
  title: 'calendar-gas schedule',
  link: 'https://calendar.google.com/',
  description: 'Events from today through the next 7 days (Asia/Tokyo).',
};

// Serves action=rss. The token check comes first and fails closed:
// an unset RSS_TOKEN refuses every request, and a mismatch answers
// a JSON refusal — never the feed.
function serveRss_(params) {
  const expected = PropertiesService.getScriptProperties().getProperty('RSS_TOKEN');
  if (!expected || typeof params.token !== 'string' || params.token !== expected) {
    return createJsonResponse_({ ok: false, error: 'Unauthorized.' });
  }
  const config = readConfig_();
  if (!config) {
    return createJsonResponse_({ ok: false, error: 'Not configured.' });
  }
  const today = todayJst_();
  const windowStart = jstTime_(today, 0);
  const windowEnd = jstTime_(addDaysStr_(today, RSS_DAYS_AHEAD_ + 1), 0);
  const items = [
    ...readFeedEvents_(config.mainId, 'main', windowStart, windowEnd),
    ...readFeedEvents_(config.familyId, 'family', windowStart, windowEnd),
  ]
    .filter((ev) => !ev.declined && ev.start >= windowStart && ev.start < windowEnd)
    .sort((a, b) => b.start - a.start)
    .slice(0, RSS_LIMIT_);
  return createXmlResponse_(buildRss_(items));
}

function readFeedEvents_(calendarId, source, start, end) {
  const calendar = CalendarApp.getCalendarById(calendarId);
  if (!calendar) return [];
  return calendar.getEvents(start, end).map((ev) => normalizeFeedEvent_(ev, source));
}

// The feed normalization keeps what an item needs (id, title,
// location) and — unlike the digest — never drops family events by
// title. Declined events are still dropped by the caller.
function normalizeFeedEvent_(ev, source) {
  let declined = false;
  if (typeof ev.getMyStatus === 'function' && typeof CalendarApp !== 'undefined' && CalendarApp.GuestStatus) {
    declined = ev.getMyStatus() === CalendarApp.GuestStatus.NO;
  }
  return {
    id: typeof ev.getId === 'function' ? ev.getId() : '',
    title: typeof ev.getTitle === 'function' ? ev.getTitle() : '',
    start: ev.getStartTime(),
    end: ev.getEndTime(),
    allDay: typeof ev.isAllDayEvent === 'function' ? ev.isAllDayEvent() : false,
    declined,
    location: typeof ev.getLocation === 'function' ? ev.getLocation() : '',
    source,
  };
}

export function buildRss_(items) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<rss version="2.0">',
    '<channel>',
    '<title>' + escapeXml_(RSS_CHANNEL_.title) + '</title>',
    '<link>' + escapeXml_(RSS_CHANNEL_.link) + '</link>',
    '<description>' + escapeXml_(RSS_CHANNEL_.description) + '</description>',
  ];
  for (const ev of items) {
    // The guid pairs the event id with its start, so a recurring
    // event's instances stay distinct and the same instance can
    // never reappear as a new article across fetches.
    const guid = `${ev.id}@${ev.start.toISOString()}`;
    lines.push(
      '<item>',
      '<title>' + escapeXml_(ev.title || '(no title)') + '</title>',
      '<link>' + escapeXml_(RSS_CHANNEL_.link) + '</link>',
      '<guid isPermaLink="false">' + escapeXml_(guid) + '</guid>',
      '<pubDate>' + ev.start.toUTCString() + '</pubDate>',
      '<description>' + escapeXml_(describeFeedEvent_(ev)) + '</description>',
      '</item>'
    );
  }
  lines.push('</channel>', '</rss>');
  return lines.join('\n');
}

const JST_WEEKDAYS_ = ['日', '月', '火', '水', '木', '金', '土'];

// JST wall-clock parts of a Date (UTC+9 shift, then UTC getters),
// so labels are right in any runtime timezone.
function jstParts_(date) {
  const t = new Date(date.getTime() + 9 * 60 * 60 * 1000);
  const pad = (n) => String(n).padStart(2, '0');
  return {
    month: t.getUTCMonth() + 1,
    day: t.getUTCDate(),
    weekday: JST_WEEKDAYS_[t.getUTCDay()],
    hhmm: `${pad(t.getUTCHours())}:${pad(t.getUTCMinutes())}`,
    dateKey: `${t.getUTCFullYear()}-${pad(t.getUTCMonth() + 1)}-${pad(t.getUTCDate())}`,
  };
}

function describeFeedEvent_(ev) {
  const s = jstParts_(ev.start);
  const head = `${s.month}月${s.day}日（${s.weekday}）`;
  let when;
  if (ev.allDay) {
    // All-day end times are exclusive: the last day is end - 1 day.
    const last = jstParts_(new Date(ev.end.getTime() - 24 * 60 * 60 * 1000));
    when = last.dateKey === s.dateKey
      ? `${head} 終日`
      : `${head}–${last.month}月${last.day}日（${last.weekday}） 終日`;
  } else {
    const e = jstParts_(ev.end);
    when = e.dateKey === s.dateKey
      ? `${head} ${s.hhmm}–${e.hhmm}`
      : `${head} ${s.hhmm} – ${e.month}月${e.day}日（${e.weekday}） ${e.hhmm}`;
  }
  return when + ' / ' + ev.source + (ev.location ? ' @ ' + ev.location : '');
}

function escapeXml_(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function createXmlResponse_(xml) {
  return ContentService
    .createTextOutput(xml)
    .setMimeType(ContentService.MimeType.XML);
}

function createJsonResponse_(obj) {
  return ContentService
    .createTextOutput(JSON.stringify(obj))
    .setMimeType(ContentService.MimeType.JSON);
}

export function setup() {
  const props = PropertiesService.getScriptProperties();
  if (!props.getProperty('API_TOKEN')) {
    props.setProperty('API_TOKEN', Utilities.getUuid() + Utilities.getUuid());
  }
  if (!props.getProperty('RSS_TOKEN')) {
    props.setProperty('RSS_TOKEN', Utilities.getUuid() + Utilities.getUuid());
  }
  console.log('API_TOKEN and RSS_TOKEN have been set. Copy them from Project Settings > Script Properties.');
}
